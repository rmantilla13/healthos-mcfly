// Writes server/portraitStyle.ts: the healthOS figure (public/figures/digital-man.webp) as base64, the style reference
// every portrait is made against. It lives in the server code because the hosted API is one esbuild bundle, which
// public/ files never reach. Run it after replacing that figure: node scripts/portrait-style.mjs
// (test/portraits.test.ts fails until the two match).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'public', 'figures', 'digital-man.webp');
const target = path.join(root, 'server', 'portraitStyle.ts');

const base64 = fs.readFileSync(source).toString('base64');
const lines = base64.match(/.{1,140}/g) ?? [];
fs.writeFileSync(
  target,
  `// Generated by scripts/portrait-style.mjs from public/figures/digital-man.webp; don't edit. The style reference for
// portraits (server/portraits.ts), kept in the server code so the hosted bundle has it.
export const STYLE_REFERENCE = { mime: 'image/webp', name: 'healthos-figure.webp' } as const;

export const STYLE_REFERENCE_BASE64 = [
${lines.map((l) => `  '${l}',`).join('\n')}
].join('');
`,
);
console.log(`Wrote ${path.relative(root, target)} (${(base64.length / 1024).toFixed(0)} KB of base64).`);
